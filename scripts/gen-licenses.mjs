// Writes src/legal/licenses.ts from the direct dependencies in package.json (name, version, licence, home page).
// Run after changing dependencies:  node scripts/gen-licenses.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const rows = Object.keys(pkg.dependencies).sort().map((name) => {
  const p = JSON.parse(readFileSync(new URL(`node_modules/${name}/package.json`, root), 'utf8'));
  const license = typeof p.license === 'string' ? p.license : p.license?.type ?? (p.licenses?.map((l) => l.type).join(' OR ') ?? 'unknown');
  const home = (p.homepage ?? (typeof p.repository === 'string' ? p.repository : p.repository?.url) ?? '').replace(/^git\+/, '').replace(/\.git$/, '');
  return { name, version: p.version, license, home };
});
const out = `// Generated by scripts/gen-licenses.mjs from the direct dependencies. Do not edit by hand.
export type LicenseEntry = { name: string; version: string; license: string; home: string };

export const LICENSES: readonly LicenseEntry[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL('src/legal/licenses.ts', root), out);
console.log(`${rows.length} packages`);
